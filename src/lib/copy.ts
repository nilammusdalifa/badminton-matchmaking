/** Every word the app shows, in one place, so wording changes happen here.
 *
 * House style, applied to everything below:
 *  - sentence case for buttons and labels ("Resume court"), en dashes for ranges (19:00–22:00, 2–7);
 *  - "match" for one contest, never "game";
 *  - "umpire" for the person who edits, never "organizer";
 *  - "queue" for the list of players waiting to be picked.
 * Things built from data (names, counts) are functions; plain text is a string. */

const count = (n: number, one: string, many: string) => `${n} ${n === 1 ? one : many}`;
export const matchCount = (n: number) => count(n, "match", "matches");
export const playerCount = (n: number) => count(n, "player", "players");
export const courtCount = (n: number) => count(n, "court", "courts");

/** "2–7", or just "2" when the two are the same. */
export const range = (min: number, max: number) => (min === max ? String(min) : `${min}–${max}`);

